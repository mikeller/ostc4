#!/usr/bin/env python3
"""Generate/check the opaque native-settings build-layout identity.

The digest covers preprocessed settings declarations, compiler identity and
the actual firmware tComm compilation flags. It is not a semantic schema.
"""
import argparse
import hashlib
import pathlib
import re
import shlex
import shutil
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
RECIPE = ROOT / "RefPrj/Firmware/Release/Discovery/Src/subdir.mk"
OUTPUT = ROOT / "Discovery/Inc/tCommConfigLayoutId.h"


def content():
    recipe = RECIPE.read_text()
    line = next(line.strip() for line in recipe.splitlines()
                if line.lstrip().startswith("arm-none-eabi-gcc "))
    args = shlex.split(line)
    flags = []
    for arg in args[1:]:
        if arg.startswith("-I"):
            flags.append(arg.replace("$(BUILD_DIR)", str(ROOT)))
        elif arg.startswith(("-D", "-m", "-O", "-f")) and "$" not in arg:
            flags.append(arg)
    # Use the compiler selected by arm_build_tools.mk through PATH.
    compiler = shutil.which("arm-none-eabi-gcc")
    if compiler is None:
        raise SystemExit("arm-none-eabi-gcc not found in PATH")
    version = subprocess.check_output([compiler, "-dumpfullversion", "-dumpversion"])
    source = subprocess.check_output([compiler, *flags, "-E", "-P", "-x", "c", "-"],
                                     input=b'#include "settings.h"\n')
    # Do not embed absolute paths or non-public material in generated files.
    stable_flags = [re.sub(re.escape(str(ROOT)), "<ROOT>", flag) for flag in flags]
    digest = hashlib.sha256(version + "\n".join(stable_flags).encode() + source).digest()[:16]
    values = ", ".join(f"0x{byte:02x}" for byte in digest)
    return ("/* Generated by Discovery/tests/config_layout_id.py. Do not edit. */\n"
            "#ifndef TCOMM_CONFIG_LAYOUT_ID_H\n#define TCOMM_CONFIG_LAYOUT_ID_H\n"
            f"#define CONFIG_LAYOUT_DIGEST {{ {values} }}\n"
            "#endif\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    expected = content()
    if options.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            parser.error("settings layout/build flags changed: regenerate the layout ID and review protocol compatibility")
    else:
        OUTPUT.write_text(expected)


if __name__ == "__main__":
    main()
